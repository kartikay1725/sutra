router = APIRouter(
    prefix="/v1/me",
    tags=["me"],
)


class MyWorkResponse(BaseModel):
    id: str
    title: str
    type: str
    repo_name: str
    status: str
    updated_at: datetime

    model_config = ConfigDict(from_attributes=True)


@router.get("/work", response_model=list[MyWorkResponse])
def get_my_work(
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    task_rows = db.execute(
        select(Task, Repository.name)
        .join(Repository, Task.repository_id == Repository.id)
        .where(
            or_(
                Task.assigned_user_id == current_user.id,
                Task.created_by == current_user.id,
                Repository.owner_id == current_user.id,
            )
        )
        .order_by(Task.updated_at.desc())
        .limit(50)
    ).all()

    results = []
    for task, repo_name in task_rows:
        results.append(
            MyWorkResponse(
                id=task.id,
                title=task.title,
                type="task",
                repo_name=repo_name,
                status=task.status,
                updated_at=task.updated_at,
            )
        )

    return results


